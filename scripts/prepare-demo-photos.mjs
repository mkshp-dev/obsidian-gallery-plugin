// Maintainer-only: turns a folder of source photos into the sample photo set the use-case notes
// download (see src/generators/SamplePhotos.ts). Not part of the plugin build.
//
//   node scripts/prepare-demo-photos.mjs <source-dir> [--credits <file.csv>] [--out <dir>]
//
// <source-dir>/credits.csv (or --credits) has the columns  file,name,set,credit,source,license
//   file     source file name, relative to <source-dir>
//   name     file name written into the vault, shown as the caption ("Skógafoss at dusk.jpg")
//   set      iceland | cabin | recipe | design
//
// Each photo is rotated upright, resized to a long edge of at most 1920 px, saved as JPEG
// (quality 80) without EXIF or other metadata, and written to <out>/<set>/<slug>.jpg. Then
// <out>/manifest.json and <out>/CREDITS.md are written. --out defaults to
// docs-site/static/demo-photos/use-cases; with the default, src/generators/SamplePhotoSet.ts is
// also updated so the consent dialog shows the right count and size.
//
// The photos still needed are listed in scripts/demo-photos.md.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_OUT = path.join(ROOT, 'docs-site/static/demo-photos/use-cases');
const CONSTANTS_FILE = path.join(ROOT, 'src/generators/SamplePhotoSet.ts');

const LONG_EDGE = 1920;
const QUALITY = 80;
const BUDGET_BYTES = 15 * 1024 * 1024;

/** Photos the use-case notes are designed around; see scripts/demo-photos.md */
const TARGETS = { iceland: 20, cabin: 10, recipe: 1, design: 8 };

// Same rules the plugin applies to the manifest (src/generators/SamplePhotos.ts)
const SET_PATTERN = /^[a-z0-9-]+$/;
const UNSAFE_NAME = /[\\/:*?"<>|#^[\]]/;

function fail(message) {
    console.error(`Error: ${message}`);
    process.exit(1);
}

function parseArgs(argv) {
    const args = { source: undefined, credits: undefined, out: DEFAULT_OUT };
    for (let i = 0; i < argv.length; i++) {
        if (argv[i] === '--credits') args.credits = argv[++i];
        else if (argv[i] === '--out') args.out = path.resolve(argv[++i]);
        else if (!args.source) args.source = path.resolve(argv[i]);
        else fail(`Unexpected argument ${argv[i]}`);
    }
    if (!args.source) fail('Usage: node scripts/prepare-demo-photos.mjs <source-dir> [--credits <file.csv>] [--out <dir>]');
    args.credits = path.resolve(args.credits ?? path.join(args.source, 'credits.csv'));
    return args;
}

/** Minimal CSV: comma separated, fields may be "quoted" with "" for a literal quote */
function parseCsv(text) {
    const rows = [];
    let row = [];
    let field = '';
    let quoted = false;
    for (let i = 0; i < text.length; i++) {
        const c = text[i];
        if (quoted) {
            if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
            else if (c === '"') quoted = false;
            else field += c;
        } else if (c === '"') quoted = true;
        else if (c === ',') { row.push(field); field = ''; }
        else if (c === '\n' || c === '\r') {
            if (c === '\r' && text[i + 1] === '\n') i++;
            row.push(field); field = '';
            if (row.some(f => f.trim() !== '')) rows.push(row);
            row = [];
        } else field += c;
    }
    row.push(field);
    if (row.some(f => f.trim() !== '')) rows.push(row);

    const [header, ...body] = rows.map(r => r.map(f => f.trim()));
    const expected = ['file', 'name', 'set', 'credit', 'source', 'license'];
    if (header?.join(',') !== expected.join(',')) fail(`credits.csv must start with the header ${expected.join(',')}`);
    return body.map((r, i) => {
        if (r.length !== expected.length) fail(`credits.csv row ${i + 2} has ${r.length} columns, expected ${expected.length}`);
        return Object.fromEntries(expected.map((key, j) => [key, r[j]]));
    });
}

// Letters that don't decompose into an ASCII letter plus accents
const TRANSLITERATE = { 'ð': 'd', 'þ': 'th', 'æ': 'ae', 'ø': 'o', 'œ': 'oe', 'ß': 'ss', 'ł': 'l', 'đ': 'd' };

const slug = name => name
    .replace(/\.[^.]+$/, '')
    .toLowerCase()
    .replace(/[ðþæøœßłđ]/g, c => TRANSLITERATE[c])
    .normalize('NFD').replace(/[̀-ͯ]/g, '')
    .toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function shape(width, height) {
    const ratio = width / height;
    if (ratio >= 2) return 'panorama';
    if (ratio > 1.05) return 'landscape';
    if (ratio < 0.95) return 'portrait';
    return 'square';
}

const escapeCell = text => text.replace(/\|/g, '\\|');

function creditsMarkdown(photos) {
    const lines = [
        '# Sample photo credits',
        '',
        'The photos the Gallery View use-case notes download. Generated by `scripts/prepare-demo-photos.mjs`; edit `credits.csv` instead.',
        ''
    ];
    for (const set of [...new Set(photos.map(p => p.set))]) {
        lines.push(`## ${set}`, '', '| Photo | Credit | Source | License |', '|---|---|---|---|');
        for (const p of photos.filter(p => p.set === set)) {
            lines.push(`| ${escapeCell(p.name)} | ${escapeCell(p.credit)} | [link](${p.source}) | ${escapeCell(p.license)} |`);
        }
        lines.push('');
    }
    return lines.join('\n');
}

async function main() {
    const args = parseArgs(process.argv.slice(2));
    if (!fs.existsSync(args.credits)) fail(`No credits file at ${args.credits}`);
    const rows = parseCsv(fs.readFileSync(args.credits, 'utf8'));
    if (rows.length === 0) fail('credits.csv lists no photos');

    // Check every row before writing anything
    const seen = new Set();
    for (const [i, row] of rows.entries()) {
        const where = `credits.csv row ${i + 2} (${row.file})`;
        for (const key of ['file', 'name', 'set', 'credit', 'source', 'license']) {
            if (!row[key]) fail(`${where}: ${key} is empty`);
        }
        if (!SET_PATTERN.test(row.set)) fail(`${where}: set may only use a-z, 0-9 and -`);
        row.name = row.name.replace(/\.(jpe?g|png|webp|heic|tiff?)$/i, '') + '.jpg';
        if (UNSAFE_NAME.test(row.name) || row.name.startsWith('.')) fail(`${where}: name "${row.name}" has characters Obsidian can't use in a file name`);
        if (!slug(row.name)) fail(`${where}: name "${row.name}" has no letters or digits`);
        const key = `${row.set}/${slug(row.name)}`;
        if (seen.has(key)) fail(`${where}: another photo in ${row.set} has the same name`);
        seen.add(key);
        if (!fs.existsSync(path.join(args.source, row.file))) fail(`${where}: source file not found`);
    }

    // The output folder is generated: clear the previous run
    fs.mkdirSync(args.out, { recursive: true });
    for (const entry of fs.readdirSync(args.out, { withFileTypes: true })) {
        if (entry.isDirectory()) fs.rmSync(path.join(args.out, entry.name), { recursive: true });
    }

    const photos = [];
    for (const row of rows) {
        const file = `${row.set}/${slug(row.name)}.jpg`;
        const target = path.join(args.out, file);
        fs.mkdirSync(path.dirname(target), { recursive: true });

        // sharp drops EXIF and other metadata unless asked to keep it; rotate() applies the EXIF orientation first
        const { data, info } = await sharp(path.join(args.source, row.file))
            .rotate()
            .resize({ width: LONG_EDGE, height: LONG_EDGE, fit: 'inside', withoutEnlargement: true })
            .jpeg({ quality: QUALITY, mozjpeg: true })
            .toBuffer({ resolveWithObject: true });
        fs.writeFileSync(target, data);

        photos.push({
            file,
            name: row.name,
            set: row.set,
            width: info.width,
            height: info.height,
            bytes: data.length,
            sha256: crypto.createHash('sha256').update(data).digest('hex'),
            credit: row.credit,
            source: row.source,
            license: row.license
        });
        console.log(`  ${file}  ${info.width}×${info.height}  ${Math.round(data.length / 1024)} KB`);
    }

    fs.writeFileSync(path.join(args.out, 'manifest.json'), JSON.stringify({ version: 1, photos }, null, 2) + '\n');
    fs.writeFileSync(path.join(args.out, 'CREDITS.md'), creditsMarkdown(photos));

    const total = photos.reduce((sum, p) => sum + p.bytes, 0);
    const megabytes = Math.ceil(total / (1024 * 1024));
    if (args.out === DEFAULT_OUT) {
        fs.writeFileSync(CONSTANTS_FILE, `\
// Written by scripts/prepare-demo-photos.mjs: the photo set published with the docs site.
// Shown in the consent dialog before anything is downloaded. Don't edit by hand.

/** Number of sample photos in the published manifest (0 until the maintainer publishes them) */
export const SAMPLE_PHOTO_COUNT = ${photos.length};

/** Total download size of the sample photos, in megabytes, rounded up */
export const SAMPLE_PHOTO_MEGABYTES = ${megabytes};
`);
    }

    console.log(`\n${photos.length} photos, ${(total / (1024 * 1024)).toFixed(1)} MB → ${path.relative(ROOT, args.out) || args.out}`);
    if (total > BUDGET_BYTES) console.warn(`Warning: over the 15 MB budget. Drop photos or lower the quality.`);

    for (const [set, target] of Object.entries(TARGETS)) {
        const inSet = photos.filter(p => p.set === set);
        const shapes = {};
        for (const p of inSet) shapes[shape(p.width, p.height)] = (shapes[shape(p.width, p.height)] ?? 0) + 1;
        const mix = Object.entries(shapes).map(([s, n]) => `${n} ${s}`).join(', ') || 'none';
        const status = inSet.length >= target ? 'ok' : `TODO: ${target - inSet.length} more needed`;
        console.log(`  ${set.padEnd(8)} ${String(inSet.length).padStart(2)}/${target}  (${mix})  ${status}`);
    }
}

main().catch(error => fail(error instanceof Error ? error.message : String(error)));
